def test_bootstrap_then_sync_dry_run(project: dict[str, Path]) -> None:
    cfg, root = project["config"], project["root"]
    out1 = root / "out1"
    rep = bootstrap(Options(cfg, dry_run=True, output=out1))
    assert sorted(rep.changed_chapters) == ["auth", "data-model", "overview"]
    assert (out1 / "docs/README.md").read_text().startswith("<!-- Generated by Fidus")
    assert "Fidus bootstrap" in (out1 / "pr-body.md").read_text()
    # dry run never touches the real docs repo
    assert not (project["docs"] / "docs").exists()

    # "Merge" the bootstrap PR by copying its output into the docs repo.
    shutil.copytree(out1 / "docs", project["docs"] / "docs")
    (project["docs"] / ".fidus").mkdir()
    shutil.copy(out1 / "state.json", project["docs"] / ".fidus/state.json")
    git(project["docs"], "add", "-A")
    git(project["docs"], "commit", "-qm", "merge bootstrap")

    # Nothing changed upstream -> no-op.
    assert run(Options(cfg, dry_run=True, output=root / "noop")).noop

    commit(
        project["app"],
        {"src/auth/login.py": "def login(user, ttl=1):\n    return True\n"},
        "feat: ttl",
    )
    commit(project["app"], {"tools/gen.py": "print(1)\n"}, "chore: tooling")
    out2 = root / "out2"
    rep = run(Options(cfg, dry_run=True, output=out2))
    assert rep.changed_chapters == ["auth"]
    state = json.loads((out2 / "state.json").read_text())
    statuses = {t["title"]: t["status"] for t in state["pending"]["triggers"]}
    assert statuses == {"feat: ttl": "applied", "chore: tooling": "unmapped"}
    body = (out2 / "pr-body.md").read_text()
    assert "Needs attention" in body and "app:tools/gen.py" in body
    assert "+- touched `app:src/auth/login.py`" in (out2 / "diff.patch").read_text()
    run_json = json.loads((out2 / "run.json").read_text())
    assert run_json["episodes"][0]["chapter_id"] == "auth"


