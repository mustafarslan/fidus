def test_local_cursor_commit_rewritten_falls_back_to_timestamp(
    project: dict[str, Path], monkeypatch: pytest.MonkeyPatch
) -> None:
    """Production path: state has cursor_sha; if that commit vanished, don't replay history."""
    out = project["root"] / "boot"
    bootstrap(Options(project["config"], dry_run=True, output=out))
    state = json.loads((out / "state.json").read_text())
    state["base"]["repos"]["local:app"]["cursor_sha"] = "0" * 40  # rewritten away
    (project["docs"] / ".fidus").mkdir()
    (project["docs"] / ".fidus/state.json").write_text(json.dumps(state))
    shutil.copytree(out / "docs", project["docs"] / "docs")
    rep = run(Options(project["config"], dry_run=True, output=project["root"] / "o2"))
    assert rep.triggers_collected == 0  # the initial commit predates the cursor timestamp
    monkeypatch.setenv("GIT_COMMITTER_DATE", "2099-01-01T00:00:00+00:00")
    commit(project["app"], {"src/db/models.py": "class M:\n    x: int\n"}, "feat: x")
    rep = run(Options(project["config"], dry_run=True, output=project["root"] / "o3"))
    assert rep.triggers_collected == 1  # only the new commit, not a replay of history


