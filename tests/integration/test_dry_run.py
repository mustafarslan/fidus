def test_audit_mode_checks_every_chapter(project: dict[str, Path]) -> None:
    out = project["root"] / "boot"
    bootstrap(Options(project["config"], dry_run=True, output=out))
    shutil.copytree(out / "docs", project["docs"] / "docs")
    (project["docs"] / ".fidus").mkdir()
    shutil.copy(out / "state.json", project["docs"] / ".fidus/state.json")
    rep = run(
        Options(project["config"], dry_run=True, output=project["root"] / "audit"), mode="audit"
    )
    assert rep.did_audit and not rep.did_sync
    assert {e.chapter_id for e in rep.episodes} == {"overview", "data-model", "auth"}
    state = json.loads((project["root"] / "audit/state.json").read_text())
    assert state["pending"]["audit"]["chapters_checked"] == ["auth", "data-model", "overview"]


def test_cli_commands(project: dict[str, Path]) -> None:
    cfg = str(project["config"])
    res = runner.invoke(cli, ["--version"])
    assert res.exit_code == 0 and "fidus" in res.output
    res = runner.invoke(cli, ["validate", "-c", cfg, "--offline"])
    assert res.exit_code == 0, res.output
    res = runner.invoke(cli, ["validate", "-c", cfg, "--offline", "--strict"])
    assert res.exit_code == 2  # chapters not written yet is a warning
    res = runner.invoke(
        cli, ["run", "-c", cfg, "--dry-run", "--output", str(project["root"] / "x")]
    )
    assert res.exit_code == 1 and "bootstrap" in res.output
    res = runner.invoke(
        cli,
        [
            "run",
            "-c",
            cfg,
            "--dry-run",
            "--since",
            "2020-01-01",
            "--output",
            str(project["root"] / "y"),
        ],
    )
    assert res.exit_code == 0, res.output
    res = runner.invoke(cli, ["doctor", "-c", cfg])
    assert res.exit_code == 0, res.output


